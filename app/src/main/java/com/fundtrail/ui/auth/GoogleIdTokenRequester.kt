package com.fundtrail.ui.auth

import android.content.Context
import android.util.Log
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.android.libraries.identity.googleid.GoogleIdTokenParsingException

/** What the Google account picker returned (#213). */
sealed interface GoogleIdTokenResult {
    data class Token(val idToken: String) : GoogleIdTokenResult
    /** The user closed the picker: not an error, nothing is shown. */
    data object Cancelled : GoogleIdTokenResult
    /** No Google account on the phone (or none usable). */
    data object NoAccount : GoogleIdTokenResult
    /** This build has no Google web client id (the Google provider isn't set up in Firebase yet). */
    data object NotConfigured : GoogleIdTokenResult
    data class Failed(val error: Throwable) : GoogleIdTokenResult
}

/**
 * Shows the system Google account picker and returns its ID token. A UI API, like a permission request: it needs an
 * Activity context to show the sheet, so it runs from the screen and hands the result to [GoogleSignInViewModel].
 */
class GoogleIdTokenRequester {

    suspend fun request(activityContext: Context): GoogleIdTokenResult {
        val webClientId = webClientId(activityContext) ?: return GoogleIdTokenResult.NotConfigured
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(
                GetGoogleIdOption.Builder()
                    .setServerClientId(webClientId)
                    .setFilterByAuthorizedAccounts(false) // offer every account, so a first sign-in works too
                    .build()
            )
            .build()
        return try {
            val credential = CredentialManager.create(activityContext).getCredential(activityContext, request).credential
            if (credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                GoogleIdTokenResult.Token(GoogleIdTokenCredential.createFrom(credential.data).idToken)
            } else {
                GoogleIdTokenResult.Failed(IllegalStateException("Unexpected credential type ${credential.type}"))
            }
        } catch (e: GetCredentialCancellationException) {
            GoogleIdTokenResult.Cancelled
        } catch (e: NoCredentialException) {
            GoogleIdTokenResult.NoAccount
        } catch (e: GetCredentialException) {
            Log.w(TAG, "Google account picker failed", e)
            GoogleIdTokenResult.Failed(e)
        } catch (e: GoogleIdTokenParsingException) {
            Log.w(TAG, "Google ID token could not be parsed", e)
            GoogleIdTokenResult.Failed(e)
        }
    }

    /**
     * `default_web_client_id` is generated by the google-services plugin only once the Google provider is enabled in
     * Firebase and `google-services.json` has its web OAuth client. Looked up at runtime so builds without it (CI,
     * a teammate's older json) still compile; the button then explains instead of crashing.
     */
    @Suppress("DiscouragedApi")
    private fun webClientId(context: Context): String? {
        val id = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        return if (id == 0) null else context.getString(id).takeIf { it.isNotBlank() }
    }

    private companion object {
        const val TAG = "GoogleIdTokenRequester"
    }
}
